type MethodInfo struct {
	MethodName     string    `json:"methodName"`
	ParamNames     []string  `json:"paramNames"`
	MethodTimeout  int       `json:"methodTimeout"`
	Help           string    `json:"help"`
	RequestSchema  ZodSchema `json:"requestSchema"`
	ResponseSchema ZodSchema `json:"responseSchema"`
	InputType      string    // Generated TypeScript type
	OutputType     string    // Generated TypeScript type
}

type Service struct {
	Name       string `json:"serviceName"`
	MultiArg   bool   `json:"multiArg"`
	Help       string `json:"help"`
	URL        string
	Interfaces []MethodInfo `json:"interfaces"`
}

type ZodSchema struct {
	Type       string               `json:"type"`
	Properties map[string]ZodSchema `json:"properties,omitempty"`
	Items      *ZodSchema           `json:"items,omitempty"`
	Values     []interface{}        `json:"values,omitempty"`
	Options    []ZodSchema          `json:"options,omitempty"`
	Value      interface{}          `json:"value,omitempty"`
	Inner      *ZodSchema           `json:"inner,omitempty"`
}

func installService(cmd *cobra.Command, args []string) {
	serviceURL := args[0]
	isGoInstall := cmd.Name() == "go"

	fmt.Printf("Installing service from URL: %s\n", serviceURL)

	// Fetch service information
	resp, err := http.Get(serviceURL)
	if err != nil {
		fmt.Printf("Error fetching service information: %v\n", err)
		return
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		fmt.Printf("Error reading service information: %v\n", err)
		return
	}

	var service Service
	err = json.Unmarshal(body, &service)
	if err != nil {
		fmt.Printf("Error parsing service information: %v\n", err)
		return
	}

	if service.Name == "" {
		fmt.Println("Error: Service name not found in the response")
		return
	}

	service.URL = serviceURL

	// Save service information
	services, err := loadServices()
	if err != nil {
		fmt.Printf("Error loading existing services: %v\n", err)
		return
	}

	// Check if service already exists
	for i, s := range services {
		if s.Name == service.Name {
			services[i] = service // Update existing service
			fmt.Printf("Service '%s' updated successfully\n", service.Name)
			err = saveServices(services)
			if err != nil {
				fmt.Printf("Error saving service information: %v\n", err)
				return
			}
			generateFile(service, isGoInstall)
			return
		}
	}

	// Add new service
	services = append(services, service)
	err = saveServices(services)
	if err != nil {
		fmt.Printf("Error saving service information: %v\n", err)
		return
	}

	fmt.Printf("Service '%s' installed successfully\n", service.Name)
	generateFile(service, isGoInstall)
}

func generateFile(service Service, isGoInstall bool) {
	if isGoInstall {
		generateGoFile(service)
	} else {
		generateTypeScriptFile(service)
	}
}

func listServices(cmd *cobra.Command, args []string) {
	fmt.Println("Listing all available services:")

	services, err := loadServices()
	if err != nil {
		fmt.Printf("Error loading services: %v\n", err)
		return
	}

	if len(services) == 0 {
		fmt.Println("No services installed")
		return
	}

	for _, service := range services {
		fmt.Printf("- %s\n", service.Name)
		fmt.Printf("  URL: %s\n", service.URL)
		if len(service.Interfaces) > 0 {
			fmt.Println("  Interfaces:")
			for _, iface := range service.Interfaces {
				fmt.Printf("    - %s\n", iface.MethodName)
			}
		}
		fmt.Println()
	}
}

func loadServices() ([]Service, error) {
	configPath := filepath.Join(os.Getenv("HOME"), ".squared", "services.json")
	data, err := os.ReadFile(configPath)
	if os.IsNotExist(err) {
		return []Service{}, nil
	} else if err != nil {
		return nil, err
	}

	var services []Service
	err = json.Unmarshal(data, &services)
	if err != nil {
		return nil, err
	}

	return services, nil
}

func saveServices(services []Service) error {
	configPath := filepath.Join(os.Getenv("HOME"), ".squared", "services.json")
	data, err := json.MarshalIndent(services, "", "  ")
	if err != nil {
		return err
	}

	err = os.MkdirAll(filepath.Dir(configPath), 0755)
	if err != nil {
		return err
	}

	return os.WriteFile(configPath, data, 0644)
}

func generateTypeScriptFile(service Service) {
	cwd, err := os.Getwd()
	if err != nil {
		fmt.Printf("Error getting current working directory: %v\n", err)
		return
	}

	genDir := filepath.Join(cwd, "gen", "rpc")
	err = os.MkdirAll(genDir, 0755)
	if err != nil {
		fmt.Printf("Error creating directory: %v\n", err)
		return
	}

	fileName := filepath.Join(genDir, fmt.Sprintf("%s.ts", strings.ToLower(service.Name)))

	funcMap := template.FuncMap{
		"toPascalCase": toPascalCase,
	}

	tmpl := template.Must(template.New("typescript").Funcs(funcMap).Parse(`
// Code generated by @squared/cli, DO NOT EDIT.
import { RPCContextClient } from "@squared/rpc-client";
import type { Context } from "@squared/context";

{{range .Interfaces}}
{{if ne .InputType "undefined"}}
export type {{toPascalCase .MethodName}}Request = {{.InputType}};
{{end}}

{{if ne .OutputType "void"}}
export type {{toPascalCase .MethodName}}Response = {{.OutputType}};
{{end}}

{{end}}

/**
 * {{.Name}} service
 */
export class {{toPascalCase .Name}}Service extends RPCContextClient {
  constructor(baseUrl: string) {
    super(baseUrl, "{{.Name}}");
  }
  {{range .Interfaces}}
  /**
   * {{.MethodName}} method
   */
  {{.MethodName}}(ctx: Context{{if ne .InputType "undefined"}}, req: {{toPascalCase .MethodName}}Request{{end}}): Promise<{{if eq .OutputType "void"}}void{{else}}{{toPascalCase .MethodName}}Response{{end}}> {
    {{if ne .InputType "undefined"}}
    return this.request(ctx, "{{.MethodName}}", req);
    {{else}}
    return this.request(ctx, "{{.MethodName}}");
    {{end}}
  }
  {{end}}
}
`))

	file, err := os.Create(fileName)
	if err != nil {
		fmt.Printf("Error creating file: %v\n", err)
		return
	}
	defer file.Close()

	for i, iface := range service.Interfaces {
		service.Interfaces[i].InputType = zodToTypeScript(iface.RequestSchema)
		service.Interfaces[i].OutputType = zodToTypeScript(iface.ResponseSchema)
	}

	err = tmpl.Execute(file, service)
	if err != nil {
		fmt.Printf("Error generating TypeScript file: %v\n", err)
		return
	}

	fmt.Printf("Generated TypeScript file: %s\n", fileName)

	// Try running Biome and suppress unnecessary errors
	runBiomeFormat(fileName)
}


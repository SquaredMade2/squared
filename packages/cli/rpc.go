// capitalizeFirst capitalizes only the first letter of the input string
func capitalizeFirst(s string) string {
	if s == "" {
		return ""
	}
	r := []rune(s)
	return string(append([]rune{unicode.ToUpper(r[0])}, r[1:]...))
}

func runBiomeFormat(fileName string) {
	cmd := exec.Command("pnpm", "format:write", fileName)
	err := cmd.Run()
	if err != nil {
		if exitErr, ok := err.(*exec.ExitError); ok {
			// Suppress the error if it's related to no files being changed
			if strings.Contains(string(exitErr.Stderr), "No files were processed") {
				fmt.Println("Biome did not apply any changes, skipping error")
				return
			}
		}
		fmt.Printf("Error running biome format: %v\n", err)
	} else {
		fmt.Printf("Biome formatting applied to: %s\n", fileName)
	}
}

func zodToTypeScript(schema ZodSchema) string {
	switch schema.Type {
	case "object":
		props := []string{}
		keys := make([]string, 0, len(schema.Properties))
		for key := range schema.Properties {
			keys = append(keys, key)
		}
		sort.Strings(keys) // Ensure keys are sorted alphabetically

		for _, key := range keys {
			value := schema.Properties[key]
			propType := zodToTypeScript(value)
			optionalPrefix := ""
			if value.Type == "optional" {
				optionalPrefix = "?"
				propType = zodToTypeScript(*value.Inner)
			}
			// Add a newline and indentation for each property
			props = append(props, fmt.Sprintf("\t%s%s: %s;", key, optionalPrefix, propType))
		}
		if len(props) == 0 {
			return "Record<string, unknown>"
		}
		return fmt.Sprintf("{\n%s\n}", strings.Join(props, "\n"))
	case "array":
		if schema.Items != nil {
			elementType := zodToTypeScript(*schema.Items)
			return fmt.Sprintf("%s[]", elementType)
		}
		return "unknown[]"
	case "string":
		return "string"
	case "number":
		return "number"
	case "boolean":
		return "boolean"
	case "date":
		return "Date"
	case "enum":
		if len(schema.Values) > 0 {
			enumValues := make([]string, len(schema.Values))
			for i, v := range schema.Values {
				enumValues[i] = fmt.Sprintf("\"%v\"", v)
			}
			return strings.Join(enumValues, " | ")
		}
		return "unknown"
	case "union":
		unionTypes := make([]string, len(schema.Options))
		for i, option := range schema.Options {
			unionTypes[i] = zodToTypeScript(option)
		}
		return fmt.Sprintf("(%s)", strings.Join(unionTypes, " | "))
	case "literal":
		if schema.Value != nil {
			return fmt.Sprintf("\"%v\"", schema.Value)
		}
		return "unknown"
	case "nullable":
		if schema.Inner != nil {
			return fmt.Sprintf("%s | null", zodToTypeScript(*schema.Inner))
		}
		return "null | unknown"
	case "optional":
		if schema.Inner != nil {
			return zodToTypeScript(*schema.Inner)
		}
		return "unknown | undefined"
	case "void":
		return "void"
	case "null":
		return "null"
	case "undefined":
		return "undefined"
	default:
		return "unknown"
	}
}

func zodToGo(schema ZodSchema) string {
	switch schema.Type {
	case "object":
		props := []string{}
		keys := make([]string, 0, len(schema.Properties))
		for key := range schema.Properties {
			keys = append(keys, key)
		}
		sort.Strings(keys) // Ensure keys are sorted alphabetically

		for _, key := range keys {
			value := schema.Properties[key]
			propType := zodToGo(value)
			// Add a newline and indentation for each property
			props = append(props, fmt.Sprintf("\t%s %s `json:\"%s\"`", strings.Title(key), propType, key))
		}
		if len(props) == 0 {
			return "map[string]interface{}"
		}
		return fmt.Sprintf("struct {\n%s\n}", strings.Join(props, "\n"))
	case "array":
		if schema.Items != nil {
			elementType := zodToGo(*schema.Items)
			return fmt.Sprintf("[]%s", elementType)
		}
		return "[]interface{}"
	case "string":
		return "string"
	case "integer":
		return "int"
	case "number":
		for _, firstProp := range schema.Properties {
			if zodToGo(firstProp) == "int" {
				return "int"
			}
			break
		}
		return "float64"
	case "boolean":
		return "bool"
	case "date":
		return "time.Time"
	case "enum":
		if len(schema.Values) > 0 {
			return "string" // In Go, enums are often represented as strings
		}
		return "interface{}"
	case "literal":
		if schema.Value != nil {
			switch v := schema.Value.(type) {
			case string:
				return "string"
			case float64:
				return "float64"
			case bool:
				return "bool"
			default:
				return fmt.Sprintf("%T", v)
			}
		}
		return "interface{}"
	case "nullable", "optional":
		if schema.Inner != nil {
			innerType := zodToGo(*schema.Inner)
			return fmt.Sprintf("*%s", innerType) // Use pointer for nullable/optional types
		}
		return "*interface{}"
	case "void":
		return "struct{}"
	case "null":
		return "nil"
	default:
		return "interface{}"
	}
}

func toPascalCase(s string) string {
	if len(s) == 0 {
		return s
	}

	// Capitalize the first letter, leave the rest unchanged
	return strings.ToUpper(string(s[0])) + s[1:]
}
